// ─── Writing ─────────────────────────────────────────────────────────────────

// YAML for flat frontmatter: strings JSON-quoted (valid YAML), lists inline.
const yamlValue = (value: unknown): string =>
  Array.isArray(value) ? `[${value.map(v => JSON.stringify(v)).join(', ')}]` : JSON.stringify(value)

const render = ({ frontmatter, body }: Case) =>
  `---\n${Object.entries(frontmatter)
    .map(([key, value]) => `${key}: ${yamlValue(value)}`)
    .join('\n')}\n---\n\n${body}\n`

const check = process.argv.includes('--check')
const stale: string[] = []
for (const c of CASES) {
  const path = join(ROOT, 'evals', c.dir, 'prompt.md')
  const text = render(c)
  const current = existsSync(path) ? readFileSync(path, 'utf8') : undefined
  if (current === text) continue
  if (check) {
    stale.push(path)
    continue
  }
  mkdirSync(dirname(path), { recursive: true })
  writeFileSync(path, text)
  console.log(`wrote ${path}`)
}
if (check && stale.length > 0) {
  console.error(`Stale eval prompts (run: bun scripts/build-evals.ts):\n${stale.map(p => `  - ${p}`).join('\n')}`)
  process.exit(1)
}
if (check) console.log('ok: generated eval prompts match hooks/prompts/')
